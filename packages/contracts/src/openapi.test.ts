import { describe, expect, it } from "vitest";
import { apiErrorSchema } from "./index.js";
import { createOpenApiDocument } from "./openapi.js";

describe("OpenAPI contract", () => {
  it("publishes OpenAPI 3.1 with cookie authentication and stable errors", () => {
    const document = createOpenApiDocument("test-sha");
    expect(document.openapi).toBe("3.1.0");
    expect(document.info.version).toBe("test-sha");
    expect(document.paths["/v1/auth/login"].post.responses["202"]).toBeDefined();
    expect(document.paths["/v1/tenants/{tenantId}/overview"].get.operationId).toBe(
      "getTenantOverview",
    );
    expect(document.paths["/v1/tenants/{tenantId}/invitations"].post.operationId).toBe(
      "createTenantInvitation",
    );
    expect(
      document.paths["/v1/tenants/{tenantId}/invitations/{invitationId}"].delete.operationId,
    ).toBe("revokeTenantInvitation");
    expect(document.paths["/v1/tenants/{tenantId}/members/{userId}"].patch.operationId).toBe(
      "updateTenantMember",
    );
    expect(document.paths["/v1/tenants/{tenantId}/members/{userId}/profile"].put.operationId).toBe(
      "updateTenantMemberProfile",
    );
    expect(document.paths["/v1/tenants/{tenantId}/borrowers"].get.operationId).toBe(
      "listBorrowers",
    );
    expect(document.paths["/v1/tenants/{tenantId}/borrowers"].post.operationId).toBe(
      "createBorrower",
    );
    expect(
      document.paths["/v1/tenants/{tenantId}/borrowers/{borrowerId}/review"].patch.operationId,
    ).toBe("reviewBorrowerIdentity");
    expect(
      document.paths["/v1/tenants/{tenantId}/borrowers/{borrowerId}/documents"].post.operationId,
    ).toBe("uploadBorrowerDocument");
    expect(
      document.paths["/v1/tenants/{tenantId}/borrowers/{borrowerId}/documents/{documentId}"].get
        .operationId,
    ).toBe("getBorrowerDocument");
    expect(
      document.paths["/v1/tenants/{tenantId}/members/{userId}/profile-photo"].post.operationId,
    ).toBe("uploadTenantMemberProfilePhoto");
    expect(document.paths["/v1/tenants/{tenantId}/loan-products"].post.operationId).toBe(
      "createLoanProductDraft",
    );
    expect(
      document.paths["/v1/tenants/{tenantId}/loan-products/{productId}/review"].post.operationId,
    ).toBe("submitLoanProductForReview");
    expect(
      document.paths["/v1/tenants/{tenantId}/loan-products/{productId}"].patch.operationId,
    ).toBe("updateLoanProductDraft");
    expect(
      document.paths["/v1/tenants/{tenantId}/loan-products/{productId}/schedule-preview"].post
        .operationId,
    ).toBe("previewLoanProductSchedule");
    expect(document.paths["/v1/tenants/{tenantId}/loan-applications"].post.operationId).toBe(
      "createLoanApplication",
    );
    expect(document.paths["/v1/tenants/{tenantId}/credit-analytics"].get.operationId).toBe(
      "getCreditAnalytics",
    );
    expect(
      document.paths["/v1/tenants/{tenantId}/loan-applications/{applicationId}/submit"].post
        .operationId,
    ).toBe("submitLoanApplicationForReview");
    expect(
      document.paths["/v1/tenants/{tenantId}/loan-applications/{applicationId}/review"].post
        .operationId,
    ).toBe("startLoanApplicationReview");
    expect(
      document.paths["/v1/tenants/{tenantId}/loan-applications/{applicationId}/approve"].post
        .operationId,
    ).toBe("approveLoanApplication");
    expect(document.paths["/v1/tenants/{tenantId}/settings"].patch.operationId).toBe(
      "updateTenantSettings",
    );
    expect(document.paths["/v1/tenants/{tenantId}/branches"].post.operationId).toBe(
      "createTenantBranch",
    );
    expect(document.paths["/v1/tenants/{tenantId}/teams"].post.operationId).toBe(
      "createTenantTeam",
    );
    expect(
      document.paths["/v1/tenants/{tenantId}/branches/{branchId}/status"].patch.operationId,
    ).toBe("updateTenantBranchStatus");
    expect(document.paths["/v1/tenants/{tenantId}/teams/{teamId}/status"].patch.operationId).toBe(
      "updateTenantTeamStatus",
    );
    expect(
      document.paths["/v1/tenants/{tenantId}/verification-network/query"].post.operationId,
    ).toBe("queryVerificationNetwork");
    expect(
      document.paths["/v1/tenants/{tenantId}/verification-network/corrections"].post.operationId,
    ).toBe("openVerificationNetworkCorrection");
    expect(
      document.paths["/v1/tenants/{tenantId}/verification-network/consents/{consentId}"].delete
        .operationId,
    ).toBe("revokeVerificationNetworkConsent");
    expect(
      document.paths["/v1/tenants/{tenantId}/teams/{teamId}/members/{userId}"].put.operationId,
    ).toBe("addTenantTeamMember");
    expect(
      document.paths["/v1/tenants/{tenantId}/teams/{teamId}/members/{userId}"].delete.operationId,
    ).toBe("removeTenantTeamMember");
    expect(document.paths["/v1/platform/overview"].get.operationId).toBe("getPlatformOverview");
    expect(document.paths["/v1/platform/system-status"].get.operationId).toBe(
      "getPlatformSystemStatus",
    );
    expect(document.paths["/v1/platform/tenants"].get.operationId).toBe("listPlatformTenants");
    expect(document.paths["/v1/platform/tenants"].post.operationId).toBe("createPlatformTenant");
    expect(document.paths["/v1/platform/users"].get.operationId).toBe("listPlatformUsers");
    expect(document.paths["/v1/platform/subscriptions"].get.operationId).toBe(
      "listPlatformSubscriptions",
    );
    expect(document.paths["/v1/platform/subscriptions"].post.operationId).toBe(
      "createPlatformSubscription",
    );
    expect(document.paths["/v1/platform/subscriptions/{subscriptionId}"].patch.operationId).toBe(
      "updatePlatformSubscription",
    );
    expect(document.paths["/v1/platform/users/{userId}/status"].patch.operationId).toBe(
      "updatePlatformUserStatus",
    );
    expect(document.paths["/v1/platform/tenants/{tenantId}/status"].patch.operationId).toBe(
      "updatePlatformTenantStatus",
    );
    expect(
      document.paths["/v1/platform/tenants/{tenantId}/membership-plan"].patch.operationId,
    ).toBe("updatePlatformMembershipPlan");
    expect(
      document.paths["/v1/platform/tenants/{tenantId}/membership-entitlement"].patch.operationId,
    ).toBe("updatePlatformMembershipEntitlement");
    expect(document.paths["/v1/platform/support-access"].get.operationId).toBe(
      "listPlatformSupportAccess",
    );
    expect(document.paths["/v1/platform/activity"].get.operationId).toBe("listPlatformActivity");
    expect(document.components.securitySchemes.cookieAuth.name).toBe("cobranzapp_session");
    expect(
      apiErrorSchema.safeParse({ error: { code: "AUTH_REQUIRED", message: "x" } }).success,
    ).toBe(false);
  });
});
